#!/usr/bin/env node
/**
 * Copies the Fingers RPC v1 contract from veyraco/platform into this repository:
 * the four JSON Schemas become packages/coding-agent/src/modes/rpc/managed/contract-schemas.ts and the golden
 * transcripts go to packages/coding-agent/test/fixtures/fingers-rpc/. The platform repository is the source
 * of truth; never edit the copies by hand.
 *
 * Usage: node scripts/sync-fingers-rpc-contract.mjs <path to a veyraco/platform checkout>
 */
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const platform = process.argv[2];
if (!platform) {
	console.error("Usage: node scripts/sync-fingers-rpc-contract.mjs <platform checkout>");
	process.exit(1);
}
const contract = join(platform, "contracts", "v1");
const commit = execFileSync("git", ["-C", platform, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();

const schemas = {
	command: "fingers-rpc-command.schema.json",
	response: "fingers-rpc-response.schema.json",
	event: "fingers-rpc-event.schema.json",
	common: "fingers-rpc-common.schema.json",
};
const lines = [
	"// Generated by scripts/sync-fingers-rpc-contract.mjs from veyraco/platform contracts/v1/schemas",
	`// at ${commit}. Do not edit: change the contract in veyraco/platform and sync again.`,
	'import type { JsonSchema } from "@veyraco/fingers-schema";',
	"",
];
for (const [name, file] of Object.entries(schemas)) {
	const schema = JSON.parse(readFileSync(join(contract, "schemas", file), "utf8"));
	lines.push(`export const ${name}Schema: JsonSchema = ${JSON.stringify(schema, null, "\t")};`, "");
}
lines.push(`export const contractSchemaFiles = ${JSON.stringify(schemas)} as const;`, "");
lines.push(`export const contractSourceCommit = ${JSON.stringify(commit)};`, "");
writeFileSync(join(root, "packages/coding-agent/src/modes/rpc/managed/contract-schemas.ts"), lines.join("\n"));

const fixtures = join(root, "packages/coding-agent/test/fixtures/fingers-rpc");
mkdirSync(fixtures, { recursive: true });
for (const file of readdirSync(join(contract, "testdata", "fingers-rpc"))) {
	copyFileSync(join(contract, "testdata", "fingers-rpc", file), join(fixtures, file));
}
copyFileSync(join(contract, "fingers-rpc-mapping.json"), join(fixtures, "mapping.json"));
console.log(`Synced Fingers RPC v1 contract at ${commit}.`);
